'use client';

import { useQuery } from '@tanstack/react-query';
import AdminLayout from '@/components/admin/AdminLayout';
import { AdminQueryError, EmptyState, PageHeader } from '@/components/admin/ui';
import { supabase } from '@/lib/supabase';
import { formatOrderTimestamp } from '@/lib/utils';

type AuditRow = {
  id: number;
  occurred_at: string;
  actor_id: string | null;
  table_name: string;
  operation: string;
  record_id: string | null;
};

export default function AuditLogPage() {
  const query = useQuery({
    queryKey: ['admin-audit-log'],
    queryFn: async (): Promise<AuditRow[]> => {
      const { data, error } = await supabase
        .from('admin_audit_log')
        .select('id, occurred_at, actor_id, table_name, operation, record_id')
        .order('occurred_at', { ascending: false })
        .limit(500);
      if (error) throw new Error(error.message);
      return (data || []) as AuditRow[];
    },
    staleTime: 15_000,
  });

  return (
    <AdminLayout title="Operational audit log">
      <div className="space-y-4">
        <PageHeader title="Operational audit log" subtitle="The latest 500 database changes. Entries are immutable and generated by Supabase." />
        <AdminQueryError error={query.error} onRetry={() => { void query.refetch(); }} />
        {!query.isLoading && !query.error && (query.data?.length || 0) === 0 ? (
          <EmptyState title="No changes recorded yet" subtitle="New operational changes will appear here." />
        ) : (
          <div className="ad-table-wrap border-2 border-ad-line">
            <table className="ad-table">
              <thead><tr><th>Time</th><th>Area</th><th>Action</th><th>Record</th><th>Actor</th></tr></thead>
              <tbody>{(query.data || []).map((row) => (
                <tr key={row.id}>
                  <td className="whitespace-nowrap">{formatOrderTimestamp(row.occurred_at)}</td>
                  <td>{row.table_name.replaceAll('_', ' ')}</td>
                  <td><span className="ad-tag ad-tag-outline">{row.operation}</span></td>
                  <td className="ad-num">{row.record_id || '—'}</td>
                  <td className="ad-num text-[12px]">{row.actor_id ? row.actor_id.slice(0, 8) : 'System'}</td>
                </tr>
              ))}</tbody>
            </table>
          </div>
        )}
      </div>
    </AdminLayout>
  );
}
